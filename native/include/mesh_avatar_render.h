/* Optional headless rendering extension to mesh_avatar.h.
 * Build the library with --features render before linking these functions.
 * The default CPU-only library does NOT export them. Including this header
 * requires no macro and does not enable the library feature.
 *
 * Renderers use opaque never-reused tokens and per-renderer serialization.
 * They reference an avatar token without owning it; destroy renderers before
 * destroying their avatar. Rendering reads the cached frame without ticking.
 * Raw geometry borrowers must still synchronize their reads against tick/destroy.
 * All renderer functions use the core MaStatus and thread-local last-error API.
 * Recover from a contained GPU panic by destroying/reopening the affected objects.
 * Destroy all avatars/renderers before unloading the library.
 */


